// Контракт «мир ↔ существо»: что мир сообщает существу и что получает назад.
// Мир (игра на Unity или тестовая арена) наполняет Sense сам — движок не
// знает ни о коллайдерах, ни о комнатах, ни о пикселях.

namespace Dioma.Body
{
    /// Ощущения одного тика. Все каналы нормированы в [0, 1].
    public struct Sense
    {
        /// Запах еды слева/справа. Это ГРАДИЕНТ: прямо по курсу оба канала
        /// малы — существо различает сторону, а не наличие (см. TestArena).
        public float SmellL, SmellR;
        /// Близость стены слева/справа (1 = вплотную).
        public float WallL, WallR;
        /// Зрение слева/справа (дальше обоняния, узкий конус).
        public float VisL, VisR;
        /// Еда в радиусе укуса — существо МОЖЕТ есть (захочет ли, решает тело).
        public bool FoodNear;
        /// Движение было заблокировано стеной в прошлом тике (боль).
        public bool WallHit;
    }

    /// Двигательный выход одного тика.
    public struct MotorAction
    {
        /// Поворот: −1 влево … +1 вправо (от асимметрии моторных пулов).
        public float Steer;
        /// Тяга 0..1 — из моторного тонуса КРОВИ, а не из спайков:
        /// голодный рвётся, сытый ленится, раненый едва ползёт.
        public float Drive;
        /// Кусать (еда рядом И тело голодно).
        public bool Eat;
        /// Существо спит: мир не должен его двигать/кормить.
        public bool Asleep;
    }
}
