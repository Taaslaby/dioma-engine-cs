// Сменный вычислитель мембраны. Спайковая динамика — единственное место,
// где движок тратит время всерьёз (десятки тысяч синапсов × 100 подшагов на
// тик), поэтому она вынесена за интерфейс: обычный C# для отладки и
// детерминизма, Burst — для арен с десятками существ.
//
// Контракт узкий намеренно: кернел считает МЕМБРАНУ и рассылку спайков и
// больше ничего. Пластичность, гомеостаз, награды, сон и наследственность
// остаются в `DiomaBrain` — они дешёвые (проход по синапсам раз в тик против
// ста проходов мембраны) и завязаны на семантику, которую незачем
// дублировать в каждом кернеле.

using System;

namespace Dioma.Spikes
{
    /// Неизменная часть мозга: топология и параметры модели. Кернел получает
    /// её один раз при создании, дальше меняются только веса (через
    /// `SyncWeights` после дофамина) и состояние.
    public sealed class SpikeLayout
    {
        public int N;
        public int[] RowPtr;      // CSR: N+1
        public int[] ColIdx;      // CSR: синапсы
        public float[] Nt;        // ±1 на нейрон (знак пресинапса)
        public float TimeFactor;  // dt / tau_m
        public float SynDecay;    // 1 − dt/tau_syn
        public float RefrSteps;   // round(tau_ref / dt)
        public float VRest, VThresh, VReset;
        public int RingSize;      // round(t_delay / dt) + 1

        /// Какую модель мембраны считать и с какими параметрами. Производные
        /// величины выше дублируют её поля — они остались для Burst-кернела,
        /// который читает плоские float в job-структуру.
        public NeuronModel Model;
        public NeuronParams Neuron;

        /// Per-neuron параметры HAAP: n × HaapCols.N, строка на нейрон
        /// (архетип региона × гены каналов). Заполняется только для
        /// Model == Haap; остальные модели читают общий Neuron.
        public float[] HaapProfile;
    }

    /// Вычислитель мембраны. Спайки возвращаются ИСТОРИЕЙ за тик, а не по
    /// одному подшагу: внутри тика веса константны (награды и гомеостаз живут
    /// на границах тиков), поэтому кернел вправе прогнать все подшаги подряд,
    /// а пластичность потом доигрывается по записанной истории. Для Burst это
    /// разница между одним переходом в нативный код за тик и сотней.
    public interface ISpikeKernel : IDisposable
    {
        /// Имя для логов и выбора режима («managed», «burst»).
        string Name { get; }

        /// Веса CSR внутри кернела. Их правит пластичность снаружи, поэтому
        /// после каждой награды вызывающий делает `SyncWeights`.
        void SyncWeights(float[] values);

        /// Прогнать `steps` подшагов при постоянном внешнем токе.
        /// `history` длиной `steps × N` заполняется спайками (0/1):
        /// подшаг `s`, нейрон `i` → `history[s * N + i]`.
        void Run(float[] ext, int steps, byte[] history);

        /// Скопировать «напряжение» всех нейронов — первый слот состояния
        /// модели (мембрана у LIF, след у SRM0). Для визуализации; на
        /// динамику не влияет. `into` длиной N.
        void ReadMembrane(float[] into);
    }
}
